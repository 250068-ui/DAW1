/* Ejemplo de operadores. Programa en el que se declaran las variables entre x e y.
 *  Les asignamos los valores 1000 y 2000 respectivamente.
 *  A continuacion mostramos por pantalla el valor de cada variable, la suma, la resta, la multiplicacion, la division y el resto.
 */

public class Ejemplo4{
	
	
	public static void main (String[] args){
		
		int x = 1000;
		int y = 2000;
		
		
		System.out.println("Valor de x: " + x);
		System.out.println("Valor de y: " + y);
		System.out.println("La suma de x + y = " + (x + y));
		System.out.println(x - y);
		System.out.println(x / y);
		System.out.println(x * y);
		System.out.println(x % y);
		
		
		
		


		
	}
	
}
